import Foundation

private struct ProtocolSchema: Decodable {
    let source: Source
    let messages: [Message]

    struct Source: Decodable {
        let name: String
        let version: String
        let url: String
        let sha256: String
        let license: String
    }

    struct Message: Decodable {
        let name: String
        let direction: String
        let messageID: UInt16?
        let fields: [Field]
    }

    struct Field: Decodable {
        let name: String
        let type: String
        let count: Int?
    }
}

private enum GeneratorError: Error, CustomStringConvertible {
    case missingArgument(String)
    case invalidSchema(String)
    case outputOutOfDate(String)

    var description: String {
        switch self {
        case let .missingArgument(argument):
            "Missing required argument: \(argument)"
        case let .invalidSchema(reason):
            "Invalid protocol schema: \(reason)"
        case let .outputOutOfDate(path):
            "Generated protocol source is out of date: \(path)"
        }
    }
}

@main
private enum SpiceProtocolGenerator {
    static func main() throws {
        let arguments = Array(CommandLine.arguments.dropFirst())
        let schemaPath = try value(after: "--schema", in: arguments)
        let outputPath = try value(after: "--output", in: arguments)
        let checkOnly = arguments.contains("--check")

        let schemaData = try Data(contentsOf: URL(filePath: schemaPath))
        let schema = try JSONDecoder().decode(ProtocolSchema.self, from: schemaData)
        try validate(schema)

        let rendered = render(schema)
        let outputURL = URL(filePath: outputPath)

        if checkOnly {
            let existing = try Data(contentsOf: outputURL)
            guard existing == Data(rendered.utf8) else {
                throw GeneratorError.outputOutOfDate(outputPath)
            }
        } else {
            try Data(rendered.utf8).write(to: outputURL, options: .atomic)
        }
    }

    private static func value(after flag: String, in arguments: [String]) throws -> String {
        guard let index = arguments.firstIndex(of: flag), arguments.indices.contains(index + 1) else {
            throw GeneratorError.missingArgument(flag)
        }
        return arguments[index + 1]
    }

    private static func validate(_ schema: ProtocolSchema) throws {
        guard schema.source.sha256.count == 64 else {
            throw GeneratorError.invalidSchema("source sha256 must contain 64 hexadecimal characters")
        }
        guard Set(schema.messages.map(\.name)).count == schema.messages.count else {
            throw GeneratorError.invalidSchema("message names must be unique")
        }

        let validDirections = Set([
            "link", "structure", "serverCommon", "clientCommon", "serverMain", "clientMain",
            "serverDisplay", "clientDisplay",
            "clientInputs", "serverInputs",
        ])
        let validTypes = Set([
            "uint8", "uint16", "uint32", "uint64", "int32", "fixedBytes", "channelIDs",
        ])

        for message in schema.messages {
            guard validDirections.contains(message.direction) else {
                throw GeneratorError.invalidSchema("unknown direction \(message.direction)")
            }
            guard Set(message.fields.map(\.name)).count == message.fields.count else {
                throw GeneratorError.invalidSchema("duplicate field in \(message.name)")
            }
            for field in message.fields {
                guard validTypes.contains(field.type) else {
                    throw GeneratorError.invalidSchema("unknown field type \(field.type)")
                }
                if field.type == "fixedBytes", field.count == nil || field.count! < 0 {
                    throw GeneratorError.invalidSchema("fixedBytes requires a nonnegative count")
                }
            }
        }
    }

    private static func render(_ schema: ProtocolSchema) -> String {
        var lines: [String] = [
            "// Generated by SpiceProtocolGenerator. Do not edit.",
            "// Source: \(schema.source.name) \(schema.source.version)",
            "// URL: \(schema.source.url)",
            "// SHA-256: \(schema.source.sha256)",
            "// License: \(schema.source.license)",
            "",
            "import Foundation",
            "import SpiceWire",
            "",
            "package enum SpiceMessageDirection: Sendable {",
            "    case link",
            "    case structure",
            "    case serverCommon",
            "    case clientCommon",
            "    case serverMain",
            "    case clientMain",
            "    case serverDisplay",
            "    case clientDisplay",
            "    case clientInputs",
            "    case serverInputs",
            "}",
            "",
            "package protocol SpiceGeneratedMessage: Sendable, Equatable {",
            "    static var direction: SpiceMessageDirection { get }",
            "    static var messageID: UInt16? { get }",
            "    static var minimumWireSize: Int { get }",
            "",
            "    static func decode(from reader: inout ByteReader) throws(WireError) -> Self",
            "    func encode(to writer: inout ByteWriter) throws(WireError)",
            "}",
            "",
        ]

        for message in schema.messages {
            lines.append(contentsOf: render(message))
            lines.append("")
        }
        return lines.joined(separator: "\n") + "\n"
    }

    private static func render(_ message: ProtocolSchema.Message) -> [String] {
        let minimumSize = message.fields.reduce(0) { $0 + minimumWireSize(of: $1) }
        let messageID = message.messageID.map(String.init) ?? "nil"
        var lines = [
            "package struct \(message.name): SpiceGeneratedMessage {",
            "    package static let direction: SpiceMessageDirection = .\(message.direction)",
            "    package static let messageID: UInt16? = \(messageID)",
            "    package static let minimumWireSize = \(minimumSize)",
            "",
        ]

        for field in message.fields {
            lines.append("    package let \(field.name): \(swiftType(of: field))")
        }

        if !message.fields.isEmpty {
            lines.append("")
        }
        lines.append(contentsOf: renderInitializer(message))
        lines.append("")
        lines.append(contentsOf: renderDecode(message))
        lines.append("")
        lines.append(contentsOf: renderEncode(message))
        lines.append("}")
        return lines
    }

    private static func renderInitializer(_ message: ProtocolSchema.Message) -> [String] {
        if message.fields.isEmpty {
            return ["    package init() {}"]
        }

        var lines = ["    package init("]
        for (index, field) in message.fields.enumerated() {
            let suffix = index == message.fields.count - 1 ? "" : ","
            lines.append("        \(field.name): \(swiftType(of: field))\(suffix)")
        }
        lines.append("    ) {")
        for field in message.fields {
            lines.append("        self.\(field.name) = \(field.name)")
        }
        lines.append("    }")
        return lines
    }

    private static func renderDecode(_ message: ProtocolSchema.Message) -> [String] {
        var lines = [
            "    package static func decode(",
            "        from reader: inout ByteReader",
            "    ) throws(WireError) -> Self {",
        ]

        if message.fields.isEmpty {
            lines.append("        Self()")
        } else {
            for field in message.fields where field.type == "channelIDs" {
                lines.append("        let \(field.name)CountValue = try reader.readUInt32LE()")
                lines.append("        guard let \(field.name)Count = Int(exactly: \(field.name)CountValue) else {")
                lines.append("            throw .integerOverflow")
                lines.append("        }")
                lines.append("        guard \(field.name)Count <= reader.remainingCount / SpiceChannelID.minimumWireSize else {")
                lines.append("            throw .invalidSize(\(field.name)Count)")
                lines.append("        }")
                lines.append("        var \(field.name): [SpiceChannelID] = []")
                lines.append("        \(field.name).reserveCapacity(\(field.name)Count)")
                lines.append("        for _ in 0..<\(field.name)Count {")
                lines.append("            \(field.name).append(try SpiceChannelID.decode(from: &reader))")
                lines.append("        }")
            }
            lines.append("        return Self(")
            for (index, field) in message.fields.enumerated() {
                let suffix = index == message.fields.count - 1 ? "" : ","
                let value = decodeExpression(for: field)
                lines.append("            \(field.name): \(value)\(suffix)")
            }
            lines.append("        )")
        }
        lines.append("    }")
        return lines
    }

    private static func renderEncode(_ message: ProtocolSchema.Message) -> [String] {
        var lines = [
            "    package func encode(",
            "        to writer: inout ByteWriter",
            "    ) throws(WireError) {",
        ]
        if message.fields.isEmpty {
            lines.append("        _ = writer")
        }
        for field in message.fields {
            switch field.type {
            case "uint8":
                lines.append("        writer.writeUInt8(\(field.name))")
            case "uint16":
                lines.append("        writer.writeUInt16LE(\(field.name))")
            case "uint32":
                lines.append("        writer.writeUInt32LE(\(field.name))")
            case "uint64":
                lines.append("        writer.writeUInt64LE(\(field.name))")
            case "int32":
                lines.append("        writer.writeInt32LE(\(field.name))")
            case "fixedBytes":
                lines.append("        guard \(field.name).count == \(field.count!) else {")
                lines.append("            throw .invalidSize(\(field.name).count)")
                lines.append("        }")
                lines.append("        writer.writeBytes(\(field.name))")
            case "channelIDs":
                lines.append("        guard \(field.name).count <= Int(UInt32.max) else {")
                lines.append("            throw .integerOverflow")
                lines.append("        }")
                lines.append("        writer.writeUInt32LE(UInt32(\(field.name).count))")
                lines.append("        for channel in \(field.name) {")
                lines.append("            try channel.encode(to: &writer)")
                lines.append("        }")
            default:
                break
            }
        }
        lines.append("    }")
        return lines
    }

    private static func swiftType(of field: ProtocolSchema.Field) -> String {
        switch field.type {
        case "uint8": "UInt8"
        case "uint16": "UInt16"
        case "uint32": "UInt32"
        case "uint64": "UInt64"
        case "int32": "Int32"
        case "fixedBytes": "Data"
        case "channelIDs": "[SpiceChannelID]"
        default: "Never"
        }
    }

    private static func minimumWireSize(of field: ProtocolSchema.Field) -> Int {
        switch field.type {
        case "uint8": 1
        case "uint16": 2
        case "uint32": 4
        case "uint64": 8
        case "int32": 4
        case "fixedBytes": field.count ?? 0
        case "channelIDs": 4
        default: 0
        }
    }

    private static func decodeExpression(for field: ProtocolSchema.Field) -> String {
        switch field.type {
        case "uint8": "try reader.readUInt8()"
        case "uint16": "try reader.readUInt16LE()"
        case "uint32": "try reader.readUInt32LE()"
        case "uint64": "try reader.readUInt64LE()"
        case "int32": "try reader.readInt32LE()"
        case "fixedBytes": "try reader.readBytes(count: \(field.count!))"
        case "channelIDs": field.name
        default: "try reader.readBytes(count: 0)"
        }
    }
}
