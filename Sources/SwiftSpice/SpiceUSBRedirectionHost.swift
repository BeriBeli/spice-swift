import CUSBRedirShim
import Foundation

public enum SpiceUSBRedirectionHostError: Error, Sendable, Equatable {
    case invalidArgument
    case allocationFailed
    case backendFailure(code: Int32)
    case bufferedOutputLimitExceeded
    case deviceNotFound
    case deviceRejectedByGuest
}

/// Exact `libusbredirhost` backend for one explicitly selected USB device.
///
/// This actor never enumerates or attaches devices automatically. The embedding
/// application must obtain user authorization and pass an exact bus/address.
public actor SpiceUSBRedirectionHost {
    private final class Context: @unchecked Sendable {
        let raw: OpaquePointer

        init(raw: OpaquePointer) {
            self.raw = raw
        }

        deinit {
            spice_usbredir_host_destroy(raw)
        }
    }

    private let context: Context
    private let maximumSpicePacketBytes: Int

    public init(
        maximumBufferedBytes: Int = 16 * 1_024 * 1_024,
        maximumSpicePacketBytes: Int = 1 * 1_024 * 1_024
    ) throws(SpiceUSBRedirectionHostError) {
        guard maximumBufferedBytes > 0,
              maximumBufferedBytes <= 64 * 1_024 * 1_024,
              maximumSpicePacketBytes > 0,
              maximumSpicePacketBytes <= maximumBufferedBytes else {
            throw .invalidArgument
        }
        guard let context = spice_usbredir_host_create(maximumBufferedBytes) else {
            throw .allocationFailed
        }
        self.context = Context(raw: context)
        self.maximumSpicePacketBytes = maximumSpicePacketBytes
    }

    /// Drains the initial usbredir hello packet generated by the exact backend.
    public func initialPackets() -> [Data] {
        drainOutput()
    }

    /// Feeds bytes received from the guest and returns all immediate backend replies.
    public func receiveFromGuest(
        _ data: Data
    ) throws(SpiceUSBRedirectionHostError) -> [Data] {
        guard !data.isEmpty else { throw .invalidArgument }
        let result = data.withUnsafeBytes { bytes -> Int32 in
            guard let baseAddress = bytes.bindMemory(to: UInt8.self).baseAddress else {
                return Int32(SPICE_USBREDIR_ERROR_ARGUMENT)
            }
            return spice_usbredir_host_feed_guest(context.raw, baseAddress, bytes.count)
        }
        try Self.check(result)
        return drainOutput()
    }

    /// Attaches exactly the device selected by the application. The guest's
    /// usbredir filter is checked before libusb opens and transfers ownership.
    public func attachDevice(
        busNumber: UInt8,
        deviceAddress: UInt8
    ) throws(SpiceUSBRedirectionHostError) -> [Data] {
        try Self.check(spice_usbredir_host_attach(context.raw, busNumber, deviceAddress))
        return drainOutput()
    }

    public func detachDevice() throws(SpiceUSBRedirectionHostError) -> [Data] {
        try Self.check(spice_usbredir_host_detach(context.raw))
        return drainOutput()
    }

    /// Pumps libusb completions for a bounded interval and returns generated packets.
    public func pumpEvents(
        timeoutMilliseconds: UInt32 = 0
    ) throws(SpiceUSBRedirectionHostError) -> [Data] {
        guard timeoutMilliseconds <= 100 else { throw .invalidArgument }
        try Self.check(spice_usbredir_host_pump(context.raw, timeoutMilliseconds))
        return drainOutput()
    }

    private func drainOutput() -> [Data] {
        var packets: [Data] = []
        while spice_usbredir_host_output_size(context.raw) > 0 {
            let count = min(
                spice_usbredir_host_output_size(context.raw),
                maximumSpicePacketBytes
            )
            var packet = Data(count: count)
            let copied = packet.withUnsafeMutableBytes { bytes in
                spice_usbredir_host_take_output(
                    context.raw,
                    bytes.bindMemory(to: UInt8.self).baseAddress,
                    bytes.count
                )
            }
            guard copied > 0 else { break }
            if copied < packet.count {
                packet.removeSubrange(copied..<packet.count)
            }
            packets.append(packet)
        }
        return packets
    }

    private nonisolated static func check(
        _ result: Int32
    ) throws(SpiceUSBRedirectionHostError) {
        guard result != SPICE_USBREDIR_OK else { return }
        switch result {
        case Int32(SPICE_USBREDIR_ERROR_ARGUMENT):
            throw .invalidArgument
        case Int32(SPICE_USBREDIR_ERROR_ALLOCATION):
            throw .allocationFailed
        case Int32(SPICE_USBREDIR_ERROR_OUTPUT_LIMIT):
            throw .bufferedOutputLimitExceeded
        case Int32(SPICE_USBREDIR_ERROR_DEVICE_NOT_FOUND):
            throw .deviceNotFound
        case Int32(SPICE_USBREDIR_ERROR_DEVICE_REJECTED):
            throw .deviceRejectedByGuest
        default:
            throw .backendFailure(code: result)
        }
    }
}
